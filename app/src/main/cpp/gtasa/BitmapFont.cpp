// ---------------------------------------------------------------------------
// BitmapFont::Impl
// ---------------------------------------------------------------------------

struct BitmapFont::Impl {
    bool initialized = false;

#ifdef __ANDROID__
    GLuint textureId = 0;
    GLuint shaderProgram = 0;
    GLuint vbo = 0;
    GLint posAttrib = -1;
    GLint uvAttrib = -1;
    GLint colorUniform = -1;
    GLint resolutionUniform = -1;
    GLint samplerUniform = -1;

    static constexpr const char* kVertexShader = R"(
        attribute vec2 aPosition;
        attribute vec2 aTexCoord;
        varying vec2 vTexCoord;
        uniform vec2 uResolution;
        void main() {
            vec2 clipSpace = (aPosition / uResolution) * 2.0 - 1.0;
            gl_Position = vec4(clipSpace.x, -clipSpace.y, 0.0, 1.0);
            vTexCoord = aTexCoord;
        }
    )";

    static constexpr const char* kFragmentShader = R"(
        precision mediump float;
        varying vec2 vTexCoord;
        uniform vec4 uColor;
        uniform sampler2D uTexture;
        void main() {
            float alpha = texture2D(uTexture, vTexCoord).r;
            gl_FragColor = vec4(uColor.rgb, uColor.a * alpha);
        }
    )";

    GLuint compileShader(GLenum type, const char* source) {
        GLuint shader = glCreateShader(type);
        glShaderSource(shader, 1, &source, nullptr);
        glCompileShader(shader);
        GLint compiled = 0;
        glGetShaderiv(shader, GL_COMPILE_STATUS, &compiled);
        if (!compiled) {
            char log[512];
            glGetShaderInfoLog(shader, sizeof(log), nullptr, log);
            FONT_LOGE("BitmapFont shader compile error: %s", log);
            glDeleteShader(shader);
            return 0;
        }
        return shader;
    }

    bool createTexture() {
        // Expand 1bpp atlas to 8bpp grayscale for GL_LUMINANCE upload
        uint8_t expanded[kAtlasW * kAtlasH];
        for (int i = 0; i < kNumChars; ++i) {
            int col = i % kAtlasCols;
            int row = i / kAtlasCols;
            for (int gy = 0; gy < kGlyphH; ++gy) {
                uint8_t bits = kFontAtlas[i * kGlyphH + gy];
                for (int gx = 0; gx < kGlyphW; ++gx) {
                    int px = col * kGlyphW + gx;
                    int py = row * kGlyphH + gy;
                    expanded[py * kAtlasW + px] = (bits >> (7 - gx)) & 1 ? 255 : 0;
                }
            }
        }

        glGenTextures(1, &textureId);
        glBindTexture(GL_TEXTURE_2D, textureId);
        glTexImage2D(GL_TEXTURE_2D, 0, GL_LUMINANCE, kAtlasW, kAtlasH, 0,
                     GL_LUMINANCE, GL_UNSIGNED_BYTE, expanded);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
        glBindTexture(GL_TEXTURE_2D, 0);
        return true;
    }

    bool initShaders() {
        GLuint vs = compileShader(GL_VERTEX_SHADER, kVertexShader);
        GLuint fs = compileShader(GL_FRAGMENT_SHADER, kFragmentShader);
        if (!vs || !fs) return false;

        shaderProgram = glCreateProgram();
        glAttachShader(shaderProgram, vs);
        glAttachShader(shaderProgram, fs);
        glLinkProgram(shaderProgram);

        GLint linked = 0;
        glGetProgramiv(shaderProgram, GL_LINK_STATUS, &linked);
        if (!linked) {
            char log[512];
            glGetProgramInfoLog(shaderProgram, sizeof(log), nullptr, log);
            FONT_LOGE("BitmapFont shader link error: %s", log);
            glDeleteProgram(shaderProgram);
            shaderProgram = 0;
            return false;
        }

        posAttrib = glGetAttribLocation(shaderProgram, "aPosition");
        uvAttrib = glGetAttribLocation(shaderProgram, "aTexCoord");
        colorUniform = glGetUniformLocation(shaderProgram, "uColor");
        resolutionUniform = glGetUniformLocation(shaderProgram, "uResolution");
        samplerUniform = glGetUniformLocation(shaderProgram, "uTexture");

        glGenBuffers(1, &vbo);

        glDeleteShader(vs);
        glDeleteShader(fs);
        return true;
    }
#endif
};

BitmapFont::BitmapFont() : pImpl_(std::make_unique<Impl>()) {}

BitmapFont::~BitmapFont() {
    destroy();
}

bool BitmapFont::initialize() {
#ifdef __ANDROID__
    if (!pImpl_->createTexture()) {
        FONT_LOGE("BitmapFont: texture creation failed");
        return false;
    }
    if (!pImpl_->initShaders()) {
        FONT_LOGE("BitmapFont: shader initialization failed");
        return false;
    }
    pImpl_->initialized = true;
    FONT_LOGI("BitmapFont: initialized (atlas %dx%d, %d glyphs)", kAtlasW, kAtlasH, kNumChars);
    return true;
#else
    FONT_LOGI("BitmapFont: non-Android stub");
    return false;
#endif
}

bool BitmapFont::isReady() const {
    return pImpl_->initialized;
}

void BitmapFont::drawText(const char* text, float x, float y, float size,
                          RenderColor color, int screenWidth, int screenHeight) {
#ifdef __ANDROID__
    if (!pImpl_->initialized || !text || screenWidth <= 0 || screenHeight <= 0) return;

    float glyphW = static_cast<float>(kGlyphW) * size;
    float glyphH = static_cast<float>(kGlyphH) * size;
    float texCellW = 1.0f / static_cast<float>(kAtlasCols);
    float texCellH = 1.0f / static_cast<float>(kAtlasRows);

    glUseProgram(pImpl_->shaderProgram);
    glUniform2f(pImpl_->resolutionUniform,
                static_cast<float>(screenWidth), static_cast<float>(screenHeight));
    glUniform4f(pImpl_->colorUniform,
                color.r / 255.0f, color.g / 255.0f,
                color.b / 255.0f, color.a / 255.0f);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, pImpl_->textureId);
    glUniform1i(pImpl_->samplerUniform, 0);

    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glBindBuffer(GL_ARRAY_BUFFER, pImpl_->vbo);
    glEnableVertexAttribArray(pImpl_->posAttrib);
    glEnableVertexAttribArray(pImpl_->uvAttrib);
    glVertexAttribPointer(pImpl_->posAttrib, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), nullptr);
    glVertexAttribPointer(pImpl_->uvAttrib, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float),
                          reinterpret_cast<void*>(2 * sizeof(float)));

    float cursorX = x * screenWidth;
    float cursorY = y * screenHeight;

    for (const char* p = text; *p; ++p) {
        if (*p == '\n') {
            cursorX = x * screenWidth;
            cursorY += glyphH * 1.2f;
            continue;
        }

        unsigned char ch = static_cast<unsigned char>(*p);
        if (ch < kFirstChar || ch >= kFirstChar + kNumChars) continue;

        int idx = ch - kFirstChar;
        int col = idx % kAtlasCols;
        int row = idx / kAtlasCols;

        float u0 = col * texCellW;
        float v0 = row * texCellH;
        float u1 = u0 + texCellW;
        float v1 = v0 + texCellH;

        float x0 = cursorX;
        float y0 = cursorY;
        float x1 = cursorX + glyphW;
        float y1 = cursorY + glyphH;

        // 4 vertices x (pos.xy + uv.xy) = 16 floats for TRIANGLE_STRIP
        GLfloat verts[] = {
            x0, y0,  u0, v0,
            x1, y0,  u1, v0,
            x0, y1,  u0, v1,
            x1, y1,  u1, v1,
        };
        glBufferData(GL_ARRAY_BUFFER, sizeof(verts), verts, GL_DYNAMIC_DRAW);
        glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);

        cursorX += glyphW;
    }

    glDisableVertexAttribArray(pImpl_->posAttrib);
    glDisableVertexAttribArray(pImpl_->uvAttrib);
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindTexture(GL_TEXTURE_2D, 0);
    glDisable(GL_BLEND);
    glUseProgram(0);
#else
    (void)text; (void)x; (void)y; (void)size; (void)color;
    (void)screenWidth; (void)screenHeight;
#endif
}

float BitmapFont::measureText(const char* text, float size, int screenWidth) const {
    if (!text || screenWidth <= 0) return 0.0f;
    float glyphW = static_cast<float>(kGlyphW) * size;
    float maxW = 0.0f;
    float curW = 0.0f;
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') {
            if (curW > maxW) maxW = curW;
            curW = 0.0f;
        } else {
            curW += glyphW;
        }
    }
    if (curW > maxW) maxW = curW;
    return maxW / static_cast<float>(screenWidth);
}

void BitmapFont::destroy() {
#ifdef __ANDROID__
    if (pImpl_->textureId) {
        glDeleteTextures(1, &pImpl_->textureId);
        pImpl_->textureId = 0;
    }
    if (pImpl_->shaderProgram) {
        glDeleteProgram(pImpl_->shaderProgram);
        pImpl_->shaderProgram = 0;
    }
    if (pImpl_->vbo) {
        glDeleteBuffers(1, &pImpl_->vbo);
        pImpl_->vbo = 0;
    }
    pImpl_->initialized = false;
#endif
}

