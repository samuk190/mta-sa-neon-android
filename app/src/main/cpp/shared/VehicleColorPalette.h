inline uint8_t ClosestVehiclePalette(const VehicleRgb& color) {
    unsigned bestDistance = 3 * 255 * 255 + 1;
    uint8_t best = 0;
    for (unsigned i = 0; i < std::size(kVehiclePalette); ++i) {
        const auto& candidate = kVehiclePalette[i];
        const int r = candidate[0] - color[0], g = candidate[1] - color[1], b = candidate[2] - color[2];
        const unsigned distance = r*r + g*g + b*b;
        if (distance < bestDistance) {
            bestDistance = distance;
            best = static_cast<uint8_t>(i);
        }
    }
    return best;
}
